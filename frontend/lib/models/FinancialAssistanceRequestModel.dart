// models/financial_assistance_request_model.dart
class FinancialAssistanceRequest {
  final int requestId;
  final int parentId;
  final int childId;
  final int institutionId;
  final int requestedSessionsCount;
  final double requestedDiscountPercentage;
  final double requestedTotalAmount;
  final int parentFinancialScore;
  final String parentFinancialTier;
  final String childConditionUrgency;
  final String status;
  final int? approvedSessionsCount;
  final double? approvedDiscountPercentage;
  final double? approvedTotalAmount;
  final int? approvedByManagerId;
  final DateTime? decisionDate;
  final String? decisionNotes;
  final bool autoGenerated;
  final bool requiresDocuments;
  final List<dynamic>? documentsSubmitted;
  final int estimatedProcessingDays;
  final String? urgencyReason;
  final DateTime submittedAt;
  final DateTime createdAt;
  final DateTime updatedAt;

  FinancialAssistanceRequest({
    required this.requestId,
    required this.parentId,
    required this.childId,
    required this.institutionId,
    required this.requestedSessionsCount,
    required this.requestedDiscountPercentage,
    required this.requestedTotalAmount,
    required this.parentFinancialScore,
    required this.parentFinancialTier,
    required this.childConditionUrgency,
    required this.status,
    this.approvedSessionsCount,
    this.approvedDiscountPercentage,
    this.approvedTotalAmount,
    this.approvedByManagerId,
    this.decisionDate,
    this.decisionNotes,
    required this.autoGenerated,
    required this.requiresDocuments,
    this.documentsSubmitted,
    required this.estimatedProcessingDays,
    this.urgencyReason,
    required this.submittedAt,
    required this.createdAt,
    required this.updatedAt,
  });

  factory FinancialAssistanceRequest.fromJson(Map<String, dynamic> json) {
    return FinancialAssistanceRequest(
      requestId: json['request_id'] ?? 0,
      parentId: json['parent_id'] ?? 0,
      childId: json['child_id'] ?? 0,
      institutionId: json['institution_id'] ?? 0,
      requestedSessionsCount: json['requested_sessions_count'] ?? 0,
      requestedDiscountPercentage: json['requested_discount_percentage'] != null
          ? double.tryParse(json['requested_discount_percentage'].toString()) ?? 0
          : 0,
      requestedTotalAmount: json['requested_total_amount'] != null
          ? double.tryParse(json['requested_total_amount'].toString()) ?? 0
          : 0,
      parentFinancialScore: json['parent_financial_score'] ?? 0,
      parentFinancialTier: json['parent_financial_tier'] ?? 'tier_5_no_assistance',
      childConditionUrgency: json['child_condition_urgency'] ?? 'medium',
      status: json['status'] ?? 'draft',
      approvedSessionsCount: json['approved_sessions_count'],
      approvedDiscountPercentage: json['approved_discount_percentage'] != null
          ? double.tryParse(json['approved_discount_percentage'].toString())
          : null,
      approvedTotalAmount: json['approved_total_amount'] != null
          ? double.tryParse(json['approved_total_amount'].toString())
          : null,
      approvedByManagerId: json['approved_by_manager_id'],
      decisionDate: json['decision_date'] != null
          ? DateTime.tryParse(json['decision_date'])
          : null,
      decisionNotes: json['decision_notes'],
      autoGenerated: json['auto_generated'] ?? false,
      requiresDocuments: json['requires_documents'] ?? false,
      documentsSubmitted: json['documents_submitted'],
      estimatedProcessingDays: json['estimated_processing_days'] ?? 7,
      urgencyReason: json['urgency_reason'],
      submittedAt: DateTime.parse(json['submitted_at'] ?? DateTime.now().toIso8601String()),
      createdAt: DateTime.parse(json['created_at'] ?? DateTime.now().toIso8601String()),
      updatedAt: DateTime.parse(json['updated_at'] ?? DateTime.now().toIso8601String()),
    );
  }

  String get statusLabel {
    switch (status) {
      case 'draft':
        return 'Draft';
      case 'submitted':
        return 'Submitted';
      case 'under_review':
        return 'Under Review';
      case 'pending_documents':
        return 'Documents Required';
      case 'approved':
        return 'Approved';
      case 'partially_approved':
        return 'Partially Approved';
      case 'rejected':
        return 'Rejected';
      case 'auto_generated':
        return 'Auto-Generated';
      case 'cancelled':
        return 'Cancelled';
      default:
        return status;
    }
  }

  String get statusColor {
    switch (status) {
      case 'draft':
        return '#9CA3AF'; // gray
      case 'submitted':
        return '#3B82F6'; // blue
      case 'under_review':
        return '#F59E0B'; // yellow
      case 'pending_documents':
        return '#F97316'; // orange
      case 'approved':
        return '#10B981'; // green
      case 'partially_approved':
        return '#0D9488'; // teal
      case 'rejected':
        return '#EF4444'; // red
      case 'auto_generated':
        return '#8B5CF6'; // purple
      case 'cancelled':
        return '#6B7280'; // gray
      default:
        return '#6B7280';
    }
  }

  String get referenceNumber {
    return 'FA-${requestId.toString().padLeft(6, '0')}';
  }

  bool get isApproved => status == 'approved';
  bool get isPending => status == 'submitted' || status == 'under_review' || status == 'pending_documents';
  bool get isRejected => status == 'rejected';

  double get estimatedSavings {
    if (approvedDiscountPercentage != null) {
      return requestedTotalAmount * (approvedDiscountPercentage! / 100);
    }
    return requestedTotalAmount * (requestedDiscountPercentage / 100);
  }

  double get estimatedFinalCost {
    if (approvedTotalAmount != null) return approvedTotalAmount!;
    return requestedTotalAmount * (1 - (requestedDiscountPercentage / 100));
  }

  get assessmentType => null;
}